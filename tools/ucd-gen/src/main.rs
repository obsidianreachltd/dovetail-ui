//! Generates Dovetail's Unicode tables from the Unicode Character Database
//! (decision D0014).
//!
//! 1. Download the files listed in `FILES` from
//!    `https://www.unicode.org/Public/<version>/ucd/` into
//!    `tools/ucd/data/<version>/` (git ignores that folder).
//! 2. Run `cargo run -p ucd-gen -- <version>` from the workspace root.
//!
//! It writes:
//! - `crates/dovetail-text/src/unicode/tables.rs`: grapheme break
//!   properties, Extended_Pictographic, and Indic_Conjunct_Break.
//! - `crates/dovetail-text/tests/data/grapheme_break_test.txt`: Unicode's
//!   grapheme break conformance cases, without comments.
//! - `crates/dovetail-text/src/unicode/bidi_tables.rs`: Bidi_Class, bracket
//!   pairs, mirrored characters and Joining_Type (M13).
//! - `crates/dovetail-text/tests/data/bidi_*_sample.txt`: a sample of the
//!   bidirectional conformance cases. The whole files are read by the tests
//!   from `tools/ucd/data/<version>/` when they are there.
//!
//! The files `bidi::FILES` lists are needed too.
//!
//! Never edit the generated files by hand: change this tool and run it.

mod bidi;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// The UCD files this tool reads, by their path under `ucd/`.
const FILES: [&str; 4] = [
  "auxiliary/GraphemeBreakProperty.txt",
  "auxiliary/GraphemeBreakTest.txt",
  "emoji/emoji-data.txt",
  "DerivedCoreProperties.txt",
];

/// Each data line's code points and fields, without comments.
pub(crate) fn records(
  text: &str
) -> impl Iterator<Item = ((u32, u32), Vec<&str>)> {
  text.lines().filter_map(|line| {
    let line = line.split('#').next()?.trim();
    if line.is_empty() {
      return None;
    }
    let mut fields = line.split(';').map(str::trim);
    let range = fields.next()?;
    let (start, end) = match range.split_once("..") {
      Some((a, b)) => (a, b),
      None => (range, range),
    };
    let start = u32::from_str_radix(start, 16).ok()?;
    let end = u32::from_str_radix(end, 16).ok()?;
    Some(((start, end), fields.collect()))
  })
}

/// Joins ranges that touch and have the same value.
pub(crate) fn merge<T: PartialEq + Copy>(
  mut ranges: Vec<(u32, u32, T)>
) -> Vec<(u32, u32, T)> {
  ranges.sort_by_key(|r| r.0);
  let mut out: Vec<(u32, u32, T)> = Vec::with_capacity(ranges.len());
  for r in ranges {
    match out.last_mut() {
      Some(last) if last.2 == r.2 && last.1 + 1 == r.0 => last.1 = r.1,
      _ => out.push(r),
    }
  }
  out
}

pub(crate) fn read(
  dir: &Path,
  file: &str,
) -> Result<String, String> {
  let name = Path::new(file).file_name().expect("file name");
  let path = dir.join(name);
  std::fs::read_to_string(&path)
    .map_err(|e| format!("cannot read {} ({e}); download https://www.unicode.org/Public/<version>/ucd/{file} there", path.display()))
}

fn run(version: &str) -> Result<(), String> {
  let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
  let dir = root.join("tools/ucd/data").join(version);

  let grapheme: Vec<(u32, u32, String)> = records(&read(&dir, FILES[0])?)
    .map(|((a, b), f)| (a, b, f[0].to_owned()))
    .collect();
  let pictographic: Vec<(u32, u32, ())> = records(&read(&dir, FILES[2])?)
    .filter(|(_, f)| f[0] == "Extended_Pictographic")
    .map(|((a, b), _)| (a, b, ()))
    .collect();
  let conjunct: Vec<(u32, u32, String)> = records(&read(&dir, FILES[3])?)
    .filter(|(_, f)| f.len() >= 2 && f[0] == "InCB")
    .map(|((a, b), f)| (a, b, f[1].to_owned()))
    .collect();
  let tests: Vec<String> = read(&dir, FILES[1])?
    .lines()
    .filter_map(|l| {
      l.split('#')
        .next()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(str::to_owned)
    })
    .collect();

  // Name the property values as the Rust enums in `grapheme.rs` do.
  let mut names = BTreeMap::new();
  for (_, _, v) in &grapheme {
    names.insert(v.clone(), v.replace('_', ""));
  }
  let grapheme = merge(
    grapheme
      .into_iter()
      .map(|(a, b, v)| (a, b, intern(&names[&v])))
      .collect(),
  );
  let pictographic = merge(pictographic);
  let conjunct = merge(
    conjunct
      .into_iter()
      .map(|(a, b, v)| (a, b, intern(&v)))
      .collect(),
  );

  let mut out = String::new();
  writeln!(
    out,
    "//! Generated by `tools/ucd-gen` from the Unicode Character Database,"
  )
  .unwrap();
  writeln!(
    out,
    "//! version {version}. Do not edit: change the tool and run it (D0014)."
  )
  .unwrap();
  writeln!(out, "//!").unwrap();
  writeln!(
    out,
    "//! Unicode data is © Unicode, Inc., under the Unicode License v3: see"
  )
  .unwrap();
  writeln!(
    out,
    "//! `NOTICE` and <https://www.unicode.org/license.txt>."
  )
  .unwrap();
  writeln!(out).unwrap();
  writeln!(out, "use super::grapheme::{{Gcb, InCb}};").unwrap();
  writeln!(out).unwrap();
  writeln!(out, "/// The Unicode version the tables come from.").unwrap();
  writeln!(out, "pub const UNICODE_VERSION: &str = {version:?};").unwrap();
  writeln!(out).unwrap();
  writeln!(out, "/// Grapheme_Cluster_Break, as sorted ranges. Characters not listed are Other.").unwrap();
  writeln!(
    out,
    "pub(crate) const GRAPHEME_BREAK: &[(u32, u32, Gcb)] = &["
  )
  .unwrap();
  for (a, b, v) in &grapheme {
    writeln!(out, "  (0x{a:04X}, 0x{b:04X}, Gcb::{v}),").unwrap();
  }
  writeln!(out, "];").unwrap();
  writeln!(out).unwrap();
  writeln!(out, "/// Extended_Pictographic, as sorted ranges.").unwrap();
  writeln!(
    out,
    "pub(crate) const EXTENDED_PICTOGRAPHIC: &[(u32, u32)] = &["
  )
  .unwrap();
  for (a, b, ()) in &pictographic {
    writeln!(out, "  (0x{a:04X}, 0x{b:04X}),").unwrap();
  }
  writeln!(out, "];").unwrap();
  writeln!(out).unwrap();
  writeln!(out, "/// Indic_Conjunct_Break, as sorted ranges. Characters not listed are None.").unwrap();
  writeln!(
    out,
    "pub(crate) const INDIC_CONJUNCT_BREAK: &[(u32, u32, InCb)] = &["
  )
  .unwrap();
  for (a, b, v) in &conjunct {
    writeln!(out, "  (0x{a:04X}, 0x{b:04X}, InCb::{v}),").unwrap();
  }
  writeln!(out, "];").unwrap();

  let tables = root.join("crates/dovetail-text/src/unicode/tables.rs");
  write(&tables, &out)?;
  let mut cases = format!(
    "# Generated by tools/ucd-gen from GraphemeBreakTest-{version}.txt. Do not edit.\n"
  );
  cases.push_str("# Unicode data is (c) Unicode, Inc., under the Unicode License v3 (see NOTICE).\n");
  for t in &tests {
    cases.push_str(t);
    cases.push('\n');
  }
  let test_file =
    root.join("crates/dovetail-text/tests/data/grapheme_break_test.txt");
  write(&test_file, &cases)?;
  bidi::run(&root, &dir, version)?;
  println!(
    "Unicode {version}: {} grapheme ranges, {} pictographic ranges, {} conjunct ranges, {} test cases",
    grapheme.len(),
    pictographic.len(),
    conjunct.len(),
    tests.len()
  );
  Ok(())
}

/// Leaks a value name so it can be used as a `&'static str` in the tables.
fn intern(name: &str) -> &'static str {
  Box::leak(name.to_owned().into_boxed_str())
}

pub(crate) fn write(
  path: &PathBuf,
  text: &str,
) -> Result<(), String> {
  if let Some(parent) = path.parent() {
    std::fs::create_dir_all(parent)
      .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
  }
  std::fs::write(path, text)
    .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
  println!("wrote {}", path.display());
  Ok(())
}

fn main() -> ExitCode {
  let version = std::env::args()
    .nth(1)
    .unwrap_or_else(|| "17.0.0".to_owned());
  match run(&version) {
    Ok(()) => ExitCode::SUCCESS,
    Err(e) => {
      eprintln!("ucd-gen: {e}");
      ExitCode::FAILURE
    },
  }
}
