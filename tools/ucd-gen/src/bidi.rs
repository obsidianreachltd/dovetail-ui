//! The bidirectional and joining tables (M13, D0018), and samples of the
//! bidirectional test files.

use std::fmt::Write as _;
use std::path::Path;

use crate::{merge, read, records, write};

/// The UCD files this part reads, by their path under `ucd/`.
pub const FILES: [&str; 7] = [
  "extracted/DerivedBidiClass.txt",
  "BidiBrackets.txt",
  "BidiMirroring.txt",
  "extracted/DerivedJoiningType.txt",
  "BidiTest.txt",
  "BidiCharacterTest.txt",
  "ArabicShaping.txt",
];

/// Every how many test cases one goes into the committed sample.
const BIDI_TEST_EVERY: usize = 40;
const CHARACTER_TEST_EVERY: usize = 50;

/// The Rust name of a Bidi_Class value, from its short or long name.
fn class_name(value: &str) -> Result<&'static str, String> {
  Ok(match value {
    "L" | "Left_To_Right" => "L",
    "R" | "Right_To_Left" => "R",
    "AL" | "Arabic_Letter" => "Al",
    "EN" | "European_Number" => "En",
    "ES" | "European_Separator" => "Es",
    "ET" | "European_Terminator" => "Et",
    "AN" | "Arabic_Number" => "An",
    "CS" | "Common_Separator" => "Cs",
    "NSM" | "Nonspacing_Mark" => "Nsm",
    "BN" | "Boundary_Neutral" => "Bn",
    "B" | "Paragraph_Separator" => "B",
    "S" | "Segment_Separator" => "S",
    "WS" | "White_Space" => "Ws",
    "ON" | "Other_Neutral" => "On",
    "LRE" | "Left_To_Right_Embedding" => "Lre",
    "LRO" | "Left_To_Right_Override" => "Lro",
    "RLE" | "Right_To_Left_Embedding" => "Rle",
    "RLO" | "Right_To_Left_Override" => "Rlo",
    "PDF" | "Pop_Directional_Format" => "Pdf",
    "LRI" | "Left_To_Right_Isolate" => "Lri",
    "RLI" | "Right_To_Left_Isolate" => "Rli",
    "FSI" | "First_Strong_Isolate" => "Fsi",
    "PDI" | "Pop_Directional_Isolate" => "Pdi",
    other => return Err(format!("unknown Bidi_Class {other}")),
  })
}

/// The ranges in `@missing` lines, which give defaults: later lines win.
fn missing(text: &str) -> Vec<(u32, u32, String)> {
  text
    .lines()
    .filter_map(|l| l.strip_prefix("# @missing:"))
    .filter_map(|rest| {
      let (range, value) = rest.split_once(';')?;
      let (a, b) = range.trim().split_once("..")?;
      Some((
        u32::from_str_radix(a, 16).ok()?,
        u32::from_str_radix(b, 16).ok()?,
        value.trim().to_owned(),
      ))
    })
    .collect()
}

/// Bidi_Class for every code point except Left_To_Right, the default.
fn bidi_classes(text: &str) -> Result<Vec<(u32, u32, &'static str)>, String> {
  let mut all = vec!["L"; 0x11_0000];
  for (a, b, v) in missing(text) {
    let name = class_name(&v)?;
    all[a as usize..=b as usize].fill(name);
  }
  for ((a, b), f) in records(text) {
    let name = class_name(f[0])?;
    all[a as usize..=b as usize].fill(name);
  }
  Ok(merge(
    all
      .iter()
      .enumerate()
      .filter(|(_, v)| **v != "L")
      .map(|(c, v)| (c as u32, c as u32, *v))
      .collect(),
  ))
}

fn joining_name(value: &str) -> Result<&'static str, String> {
  Ok(match value {
    "C" | "Join_Causing" => "C",
    "D" | "Dual_Joining" => "D",
    "R" | "Right_Joining" => "R",
    "L" | "Left_Joining" => "L",
    "T" | "Transparent" => "T",
    "U" | "Non_Joining" => "U",
    other => return Err(format!("unknown Joining_Type {other}")),
  })
}

/// Keeps every `@` line and every `every`th case.
fn sample(
  text: &str,
  every: usize,
) -> String {
  let mut out = String::new();
  let mut n = 0;
  for line in text.lines() {
    let line = line.split('#').next().unwrap_or("").trim_end();
    if line.trim().is_empty() {
      continue;
    }
    if line.starts_with('@') {
      out.push_str(line);
      out.push('\n');
      continue;
    }
    if n % every == 0 {
      out.push_str(line);
      out.push('\n');
    }
    n += 1;
  }
  out
}

pub fn run(
  root: &Path,
  dir: &Path,
  version: &str,
) -> Result<(), String> {
  let classes = bidi_classes(&read(dir, FILES[0])?)?;
  let brackets: Vec<(u32, u32, bool)> = records(&read(dir, FILES[1])?)
    .map(|((a, _), f)| {
      let pair = u32::from_str_radix(f[0], 16).unwrap_or(a);
      (a, pair, f[1] == "o")
    })
    .collect();
  let mirrors: Vec<(u32, u32)> = records(&read(dir, FILES[2])?)
    .filter_map(|((a, _), f)| Some((a, u32::from_str_radix(f[0], 16).ok()?)))
    .collect();
  let mut joining = Vec::new();
  for ((a, b), f) in records(&read(dir, FILES[3])?) {
    let name = joining_name(f[0])?;
    if name != "U" {
      joining.push((a, b, name));
    }
  }
  let joining = merge(joining);
  // Read only to check it is there, as the joining data's source.
  read(dir, FILES[6])?;

  let mut out = String::new();
  let w = &mut out;
  writeln!(
    w,
    "//! Generated by `tools/ucd-gen` from the Unicode Character Database,"
  )
  .unwrap();
  writeln!(
    w,
    "//! version {version}. Do not edit: change the tool and run it (D0014)."
  )
  .unwrap();
  writeln!(w, "//!").unwrap();
  writeln!(
    w,
    "//! Unicode data is © Unicode, Inc., under the Unicode License v3: see"
  )
  .unwrap();
  writeln!(w, "//! `NOTICE` and <https://www.unicode.org/license.txt>.")
    .unwrap();
  writeln!(w).unwrap();
  writeln!(w, "use super::bidi::{{BidiClass, JoiningType}};").unwrap();
  writeln!(w).unwrap();
  writeln!(
    w,
    "/// Bidi_Class, as sorted ranges. Characters not listed are L."
  )
  .unwrap();
  writeln!(
    w,
    "pub(crate) const BIDI_CLASS: &[(u32, u32, BidiClass)] = &["
  )
  .unwrap();
  for (a, b, v) in &classes {
    writeln!(w, "  (0x{a:04X}, 0x{b:04X}, BidiClass::{v}),").unwrap();
  }
  writeln!(w, "];").unwrap();
  writeln!(w).unwrap();
  writeln!(
    w,
    "/// Bidi_Paired_Bracket: each bracket, its pair, and whether it opens."
  )
  .unwrap();
  writeln!(w, "pub(crate) const BRACKETS: &[(u32, u32, bool)] = &[").unwrap();
  for (a, b, open) in &brackets {
    writeln!(w, "  (0x{a:04X}, 0x{b:04X}, {open}),").unwrap();
  }
  writeln!(w, "];").unwrap();
  writeln!(w).unwrap();
  writeln!(
    w,
    "/// Bidi_Mirroring_Glyph: each character and its mirror image."
  )
  .unwrap();
  writeln!(w, "pub(crate) const MIRRORS: &[(u32, u32)] = &[").unwrap();
  for (a, b) in &mirrors {
    writeln!(w, "  (0x{a:04X}, 0x{b:04X}),").unwrap();
  }
  writeln!(w, "];").unwrap();
  writeln!(w).unwrap();
  writeln!(
    w,
    "/// Joining_Type, as sorted ranges. Characters not listed are U."
  )
  .unwrap();
  writeln!(
    w,
    "pub(crate) const JOINING_TYPE: &[(u32, u32, JoiningType)] = &["
  )
  .unwrap();
  for (a, b, v) in &joining {
    writeln!(w, "  (0x{a:04X}, 0x{b:04X}, JoiningType::{v}),").unwrap();
  }
  writeln!(w, "];").unwrap();
  write(
    &root.join("crates/dovetail-text/src/unicode/bidi_tables.rs"),
    &out,
  )?;

  let notice = "# Unicode data is (c) Unicode, Inc., under the Unicode License v3 (see NOTICE).\n";
  for (file, every, name) in [
    (FILES[4], BIDI_TEST_EVERY, "bidi_test_sample.txt"),
    (
      FILES[5],
      CHARACTER_TEST_EVERY,
      "bidi_character_test_sample.txt",
    ),
  ] {
    let source = Path::new(file)
      .file_name()
      .unwrap()
      .to_string_lossy();
    let mut text = format!(
      "# Generated by tools/ucd-gen: every {every}th case of {source} ({version}). Do not edit.\n"
    );
    text.push_str(notice);
    text.push_str(&sample(&read(dir, file)?, every));
    write(
      &root
        .join("crates/dovetail-text/tests/data")
        .join(name),
      &text,
    )?;
  }
  println!(
    "Unicode {version}: {} bidi class ranges, {} brackets, {} mirrors, {} joining ranges",
    classes.len(),
    brackets.len(),
    mirrors.len(),
    joining.len()
  );
  Ok(())
}
